<#
.SYNOPSIS
    Removes non-shipping material from the Fishing Idle Game MMO repository.

.DESCRIPTION
    Prepares the repository for delivery by removing three classes of file:

      1. Business and third-party reference documents that are not part of the
         software (the signed contract, the external GDD PDF).
      2. Superseded design material (the Word copy of the GDD, and the six
         planning documents that describe proposals rather than shipped
         behaviour).
      3. Local build output and scratch directories that Git already ignores
         but that would still travel inside a zipped folder.

    Class 1 and 2 are tracked by Git, so they are removed with `git rm` and
    remain recoverable from history. Class 3 is untracked and is deleted
    outright; every item in it is regenerated by a build or a tool.

    The script is a dry run by default. Nothing is touched until you pass
    -Apply, and -Apply refuses to run against a dirty working tree so that the
    removal lands as one reviewable commit.

.PARAMETER Apply
    Perform the removals. Without this the script only reports what it would do.

.PARAMETER Force
    Allow -Apply to run even though the working tree has uncommitted changes.
    Use this only when you have already reviewed those changes; the removal
    commit will otherwise be mixed in with unrelated work.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\cleanup-for-release.ps1
    Reports what would be removed, changes nothing.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\cleanup-for-release.ps1 -Apply
    Performs the removal, then leaves the deletions staged for you to review
    with `git status` and `git diff --cached` before committing.

.NOTES
    Run from anywhere; the script locates the repository root itself.
    This script has no further purpose once the cleanup commit is made and may
    be deleted along with it.
#>

[CmdletBinding()]
param(
    [switch]$Apply,
    [switch]$Force
)

$ErrorActionPreference = 'Stop'

# --------------------------------------------------------------------------
# Locate the repository root, so the script works from any working directory.
# --------------------------------------------------------------------------

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$repoRoot = Split-Path -Parent $scriptDir

if (-not (Test-Path (Join-Path $repoRoot '.git'))) {
    throw "Expected a Git repository at $repoRoot but found no .git directory."
}

Push-Location $repoRoot
try {

    # ----------------------------------------------------------------------
    # What goes, and why. Paths are repository-relative and forward-slashed so
    # they can be handed to Git verbatim.
    # ----------------------------------------------------------------------

    $trackedRemovals = @(
        @{ Path = 'Fishing_Game_Contract_v2.3.docx'
           Why  = 'Commercial agreement, not project source. Belongs with the parties, not in the delivered tree.' }

        @{ Path = "design/Robin's Club GDD.pdf"
           Why  = 'Third-party reference document used during design. Not ours to redistribute with the build.' }

        @{ Path = 'design/GDD.docx'
           Why  = 'Superseded. design/GDD.md is the maintained design document; two copies drift apart.' }

        @{ Path = 'design/cambria-cost-structure-plan.md'
           Why  = 'Proposal, not shipped behaviour. Describes a cost model that was never built.' }

        @{ Path = 'design/cambria-inspired-balance-plan.md'
           Why  = 'Proposal, not shipped behaviour. Its accepted parts are already folded into GDD.md.' }

        @{ Path = 'design/cambria-key-monetization-plan.md'
           Why  = 'Proposal, not shipped behaviour. No monetisation is implemented.' }

        @{ Path = 'design/cambria-stake-dial-collapse-plan.md'
           Why  = 'Proposal, not shipped behaviour. Never signed off; reading it as spec would mislead.' }

        @{ Path = 'design/gold-value-anchor-rebalance-plan.md'
           Why  = 'Superseded planning note. The balance it argued for is live and documented in design/balance-tables.md.' }

        @{ Path = 'design/web3-sustainability-rebalance-plan.md'
           Why  = 'Proposal, not shipped behaviour. Describes systems outside the delivered scope.' }
    )

    $untrackedRemovals = @(
        @{ Path = 'tools/__pycache__'
           Why  = 'Python bytecode cache. Regenerated on the next run of any builder.' }

        @{ Path = 'tools/_gdd_images'
           Why  = 'Intermediate page images extracted from a PDF during document work (~19 MB). Nothing reads them.' }

        @{ Path = 'client/dist'
           Why  = 'Build output. Regenerated by `npm run build`, and the committed copy is already stale.' }

        @{ Path = 'tmp'
           Why  = 'Scratch directory for document exports. Empty, and Git ignores it.' }

        @{ Path = 'output'
           Why  = 'Scratch directory for document tooling output. Empty, and Git ignores it.' }
    )

    # Not deleted: these are yours and the script will not touch them. They are
    # reported so that a folder zipped for delivery does not carry secrets.
    $secretsToCheck = @(
        'server/.env',
        'client/.env.local',
        'client/.env.production'
    )

    # ----------------------------------------------------------------------
    # Safety: -Apply against a dirty tree mixes this removal into unrelated
    # work, which is exactly what makes it hard to review or revert.
    # ----------------------------------------------------------------------

    if ($Apply -and -not $Force) {
        $dirty = git status --porcelain
        if ($dirty) {
            Write-Host ''
            Write-Host 'Working tree is not clean:' -ForegroundColor Yellow
            $dirty | ForEach-Object { Write-Host "    $_" }
            Write-Host ''
            throw 'Commit or stash your changes first, so the cleanup lands as one reviewable commit. Pass -Force to override.'
        }
    }

    $mode = if ($Apply) { 'APPLYING' } else { 'DRY RUN -- nothing will be changed' }
    Write-Host ''
    Write-Host "Fishing Idle Game MMO -- release cleanup  [$mode]" -ForegroundColor Cyan
    Write-Host "Repository: $repoRoot"
    Write-Host ''

    $removedCount = 0
    $freedBytes = 0

    function Get-PathSize {
        param([string]$Target)
        if (-not (Test-Path $Target)) { return 0 }
        $item = Get-Item -LiteralPath $Target
        if ($item.PSIsContainer) {
            $files = Get-ChildItem -LiteralPath $Target -Recurse -File -ErrorAction SilentlyContinue
            if (-not $files) { return 0 }
            return ($files | Measure-Object -Property Length -Sum).Sum
        }
        return $item.Length
    }

    # ----------------------------------------------------------------------
    # Tracked files: git rm, so history keeps a copy.
    # ----------------------------------------------------------------------

    Write-Host 'Tracked files (removed with git rm; recoverable from history)' -ForegroundColor White
    Write-Host '-------------------------------------------------------------'

    foreach ($entry in $trackedRemovals) {
        $path = $entry.Path
        if (-not (Test-Path -LiteralPath $path)) {
            Write-Host ("  skip    {0}" -f $path) -ForegroundColor DarkGray
            Write-Host ("          already gone")
            continue
        }

        $size = Get-PathSize $path
        $freedBytes += $size
        $removedCount++

        Write-Host ("  remove  {0}  ({1:N0} KB)" -f $path, ($size / 1KB)) -ForegroundColor Yellow
        Write-Host ("          {0}" -f $entry.Why) -ForegroundColor DarkGray

        if ($Apply) {
            git rm --quiet -- $path
        }
    }

    # ----------------------------------------------------------------------
    # Untracked scratch: delete outright.
    # ----------------------------------------------------------------------

    Write-Host ''
    Write-Host 'Untracked build output and scratch (deleted; regenerated on demand)' -ForegroundColor White
    Write-Host '------------------------------------------------------------------'

    foreach ($entry in $untrackedRemovals) {
        $path = $entry.Path
        if (-not (Test-Path -LiteralPath $path)) {
            Write-Host ("  skip    {0}" -f $path) -ForegroundColor DarkGray
            Write-Host ("          already gone")
            continue
        }

        $size = Get-PathSize $path
        $freedBytes += $size
        $removedCount++

        Write-Host ("  delete  {0}  ({1:N0} KB)" -f $path, ($size / 1KB)) -ForegroundColor Yellow
        Write-Host ("          {0}" -f $entry.Why) -ForegroundColor DarkGray

        if ($Apply) {
            Remove-Item -LiteralPath $path -Recurse -Force
        }
    }

    # ----------------------------------------------------------------------
    # Secrets: never deleted, always reported.
    # ----------------------------------------------------------------------

    Write-Host ''
    Write-Host 'Local environment files (NOT touched -- read this before zipping)' -ForegroundColor White
    Write-Host '-----------------------------------------------------------------'

    $foundSecrets = @()
    foreach ($path in $secretsToCheck) {
        if (Test-Path -LiteralPath $path) {
            $foundSecrets += $path
            Write-Host ("  present {0}" -f $path) -ForegroundColor Red
        }
    }

    if ($foundSecrets.Count -eq 0) {
        Write-Host '  none present' -ForegroundColor Green
    } else {
        Write-Host ''
        Write-Host '  Git ignores these, so a `git clone` or `git archive` of the repository' -ForegroundColor Red
        Write-Host '  is clean. A zipped copy of this FOLDER is not. Delete them by hand, or' -ForegroundColor Red
        Write-Host '  deliver via Git, before handing the project over.' -ForegroundColor Red
    }

    # ----------------------------------------------------------------------

    Write-Host ''
    Write-Host ('Summary: {0} item(s), {1:N1} MB' -f $removedCount, ($freedBytes / 1MB)) -ForegroundColor Cyan

    if (-not $Apply) {
        Write-Host ''
        Write-Host 'Dry run. Re-run with -Apply to perform the removal.' -ForegroundColor Cyan
    } else {
        Write-Host ''
        Write-Host 'Done. The tracked deletions are staged. Review and commit:' -ForegroundColor Green
        Write-Host '    git status'
        Write-Host '    git diff --cached --stat'
        Write-Host '    git commit -m "Remove non-shipping documents and build scratch for delivery"'
        Write-Host ''
        Write-Host 'Then confirm the project still builds and passes:' -ForegroundColor Green
        Write-Host '    npm test'
        Write-Host '    npm run build'
    }
    Write-Host ''
}
finally {
    Pop-Location
}
